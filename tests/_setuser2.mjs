import fs from "node:fs";
const oldName = "fan20071202";
const newName = "Voyager77Twt";
let p = "package.json";
let pkg = JSON.parse(fs.readFileSync(p, "utf8"));
pkg.repository.url = `https://github.com/${newName}/dsh-folder-search.git`;
pkg.homepage = `https://github.com/${newName}/dsh-folder-search#readme`;
pkg.bugs.url = `https://github.com/${newName}/dsh-folder-search/issues`;
fs.writeFileSync(p, JSON.stringify(pkg, null, 2) + "\n", "utf8");
let r = fs.readFileSync("README.md", "utf8").replaceAll(oldName, newName);
fs.writeFileSync("README.md", r, "utf8");
console.log("updated to", newName);
